        Button(
            onClick = { counter++ },
            colors = ButtonDefaults.buttonColors(containerColor = Color(0xFFFF2E93))
        ) {
            Text("ইন্টারেক্টিভ অ্যাকশন (ক্লিক: ${'$'}counter)")
        }
