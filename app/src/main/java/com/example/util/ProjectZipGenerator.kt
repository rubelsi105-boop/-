package com.example.util

import android.content.Context
import android.content.Intent
import androidx.core.content.FileProvider
import com.example.model.GeneratedApp
import java.io.File
import java.io.FileOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Utility to generate and export real Android Studio source code ZIP packages
 * for any AI-created application or game.
 */
object ProjectZipGenerator {

    fun generateProjectZip(context: Context, app: GeneratedApp): File {
        val projectsDir = File(context.cacheDir, "projects").apply { mkdirs() }
        val safeFileName = app.appName.replace("[^a-zA-Z0-9]".toRegex(), "_").lowercase()
        val zipFile = File(projectsDir, "rubel_${safeFileName}_v1.0.zip")

        if (zipFile.exists()) {
            zipFile.delete()
        }

        val kotlinSourceCode = buildKotlinCode(app)
        val manifestXml = buildManifest(app)
        val buildGradle = buildGradleKts(app)
        val settingsGradle = buildSettingsGradle(app)
        val readme = buildReadme(app)

        ZipOutputStream(FileOutputStream(zipFile)).use { zos ->
            addZipEntry(zos, "${app.appName}/README.md", readme)
            addZipEntry(zos, "${app.appName}/settings.gradle.kts", settingsGradle)
            addZipEntry(zos, "${app.appName}/app/build.gradle.kts", buildGradle)
            addZipEntry(zos, "${app.appName}/app/src/main/AndroidManifest.xml", manifestXml)
            addZipEntry(zos, "${app.appName}/app/src/main/java/com/example/MainActivity.kt", kotlinSourceCode)
        }

        return zipFile
    }

    fun shareProjectZip(context: Context, app: GeneratedApp) {
        val zipFile = generateProjectZip(context, app)
        val contentUri = FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            zipFile
        )

        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/zip"
            putExtra(Intent.EXTRA_STREAM, contentUri)
            putExtra(Intent.EXTRA_SUBJECT, "Rubel AI Source Code: ${app.appName}")
            putExtra(
                Intent.EXTRA_TEXT,
                "📦 Rubel AI App Builder দিয়ে তৈরি সম্পূর্ণ Android Studio সোর্স কোড ZIP: ${app.appName}\n" +
                        "বিবরণ: ${app.description}\nক্যাটাগরি: ${app.appCategory}"
            )
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

        context.startActivity(Intent.createChooser(shareIntent, "সম্পূর্ণ সোর্স কোড ZIP ডাউনলোড ও শেয়ার করুন"))
    }

    private fun addZipEntry(zos: ZipOutputStream, path: String, content: String) {
        val entry = ZipEntry(path)
        zos.putNextEntry(entry)
        zos.write(content.toByteArray(Charsets.UTF_8))
        zos.closeEntry()
    }

    private fun buildKotlinCode(app: GeneratedApp): String {
        return """
