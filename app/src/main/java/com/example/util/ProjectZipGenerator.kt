    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
}

android {
    namespace = "com.example.generated"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.rubel.ai.${app.appName.replace("[^a-zA-Z0-9]".toRegex(), "").lowercase()}"
        minSdk = 24
        targetSdk = 35
        versionCode = 1
        versionName = "1.0"
    }

    buildFeatures {
        compose = true
    }
}

dependencies {
    implementation(platform(libs.androidx.compose.bom))
    implementation(libs.androidx.activity.compose)
    implementation(libs.androidx.compose.material3)
    implementation(libs.androidx.compose.ui)
}
""".trimIndent()
    }

    private fun buildSettingsGradle(app: GeneratedApp): String {
        return """
rootProject.name = "${app.appName}"
include(":app")
""".trimIndent()
    }

